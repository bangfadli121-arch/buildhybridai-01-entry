// Normalisasi: huruf kecil, tanda baca jadi spasi, spasi ganda diratakan.
export function normalizeItemName(nama) {
  return String(nama || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// Kategorikan nama item. Mengembalikan nama kategori, atau "Lain-lain"
// bila tidak ada keyword yang cocok.
export function categorizeItemName(nama) {
  const normalized = normalizeItemName(nama);
  if (!normalized) return "Lain-lain";
  const padded = ` ${normalized} `;
  const squashed = normalized.replace(/\s+/g, "");
  for (const [kategori, ...keywords] of KEYWORD_MAP) {
    for (const keyword of keywords) {
      // 1) Kata/frasa utuh (batas spasi) — "teh" tidak mengenai "mentega",
      //    "gas" tidak mengenai "gula pasir".
      if (padded.includes(` ${keyword} `)) return kategori;
      // 2) Nama tanpa spasi (mis. "berasmerah", "gulapasir"): keyword
      //    menempel di awal nama, minimal 4 huruf agar tidak terlalu longgar.
      if (keyword.length >= 4 && squashed.startsWith(keyword.replace(/\s+/g, ""))) {
        return kategori;
      }
    }
  }
  return "Lain-lain";
}
